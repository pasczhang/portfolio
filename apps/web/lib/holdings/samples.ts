export function sampleBookFor(ccy: BookCcy): BookPosition[] {
  return (ccy === "HKD" ? HKD_SAMPLE_BOOK : USD_SAMPLE_BOOK).map((row) => ({ ...row }));
}

export const TEMPLATE_HEADERS = [
  "assetName",
  "assetType",
  "currency",
  "counterparty",
  "isin",
  "issueDate",
  "maturityDate",
  "parValue",
  "amortizedCost",
  "shadowMtm",
  "couponRatePct",
  "rating",
] as const;

export function templateRowsFor(ccy: BookCcy): string[][] {
  const book = sampleBookFor(ccy).slice(0, 3);
  return [
    [...TEMPLATE_HEADERS],
    ...book.map((p) =>
      TEMPLATE_HEADERS.map((key) => {
        const v = p[key as keyof BookPosition];
        return v == null ? "" : String(v);
      }),
    ),
  ];
}

